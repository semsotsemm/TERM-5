CREATE MATERIALIZED VIEW MV
    BUILD IMMEDIATE
    REFRESH COMPLETE
    START WITH SYSDATE
    NEXT SYSDATE + (2/1440)
    AS
    SELECT TAB_A.NAME AS DEPT_NAME, TAB_B.INFO AS EMP_NAME
    FROM TAB_A
    INNER JOIN TAB_B ON TAB_A.ID = TAB_B.TAB_A_ID;

SELECT * 
    FROM MV;

