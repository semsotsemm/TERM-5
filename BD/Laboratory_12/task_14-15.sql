CREATE OR REPLACE VIEW V_PRODUCTS AS
    SELECT ID, ITEM_NAME, PRICE
        FROM PRODUCTS;


CREATE OR REPLACE TRIGGER TRG_V_LAB12_INSTEAD_INSERT
    INSTEAD OF INSERT 
    ON V_PRODUCTS
    FOR EACH ROW
        BEGIN
            DBMS_OUTPUT.PUT_LINE('TRG_V_LAB12_INSTEAD_INSERT: Вставка через представление');
            INSERT INTO PRODUCTS (ID, ITEM_NAME, PRICE)
                          VALUES (:NEW.ID, :NEW.ITEM_NAME, :NEW.PRICE);
        END;
        /


INSERT INTO V_PRODUCTS (ID, ITEM_NAME, PRICE)
                VALUES (13, 'Принтер', 250.00);
SELECT * 
    FROM PRODUCTS 
    WHERE ID = 13;


UPDATE PRODUCTS 
    SET PRICE = PRICE + 1 
    WHERE ID IN (1, 2);


