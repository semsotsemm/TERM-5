-- Создать последовательность, получить несколько следующих и текущее значения --
CREATE USER AAR1 IDENTIFIED BY 12345678;
GRANT CREATE SESSION, CREATE SEQUENCE, CREATE TABLE, UNLIMITED TABLESPACE, CREATE CLUSTER,CREATE SYNONYM, CREATE PUBLIC SYNONYM, CREATE VIEW, CREATE MATERIALIZED VIEW TO AAR1;

SELECT * 
    FROM dba_users
    WHERE USERNAME = 'AAR1';


CREATE SEQUENCE S1
    START WITH 1000
    INCREMENT BY 10
    NOMINVALUE
    NOMAXVALUE
    NOCYCLE
    NOCACHE
    NOORDER;
    
SELECT S1.NEXTVAL 
    FROM dual;
SELECT S1.CURRVAL 
    FROM dual;


DROP SEQUENCE S1;
DROP USER AAR CASCADE;